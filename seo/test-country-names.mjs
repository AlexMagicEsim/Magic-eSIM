#!/usr/bin/env node
// Regression tests for customer-facing country naming.
//
// The bug these pin: `publicPackageName()` threw away the provider's correct
// name and rebuilt the title from the country code, and `countryName()` returned
// the code itself when the hand-typed dictionary missed it. Brunei — stored as
// "Brunei Darussalam 10GB 30Days" — reached the storefront as "BN 10 GB", along
// with 33 other countries and 130 of 959 cards.
//
// The landing has no bundler, so every function under test is pulled out of the
// shipped sources by name and run for real, in BOTH copies. Nothing here asserts
// on a constant; the assertions are on what the renderer returns.
//
// Run: node --test seo/test-country-names.mjs

import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tmpdir } from 'node:os';
import { writeFileSync, mkdtempSync } from 'node:fs';
import { COUNTRY_NAMES as SEO_NAMES } from './country-names.mjs';
import { buildDictionary, buildDictionaryGen, STOREFRONT_WORDING, BLOCK_RE, GEN_BLOCK_RE } from './build-country-dictionary.mjs';
import { ALL as AUTHORED_FORMS } from './countries.mjs';
import { readdirSync, existsSync } from 'node:fs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
// The storefront's one renderer since RU↔EN migration PR C (the home carried a
// second copy until then; it renders no tariffs now).
const SOURCES = {
  'assets/country-tariffs.js': join(ROOT, 'assets', 'country-tariffs.js'),
};
const CATALOGUE = join(ROOT, 'assets', 'catalog.json');

/** Pull one `function name(...){...}` out of a source file by matching braces. */
function extractFunction(src, name) {
  const start = src.indexOf(`function ${name}(`);
  assert.notEqual(start, -1, `function ${name} not found`);
  let depth = 0;
  for (let i = src.indexOf('{', start); i < src.length; i++) {
    if (src[i] === '{') depth += 1;
    else if (src[i] === '}') {
      depth -= 1;
      if (depth === 0) return src.slice(start, i + 1);
    }
  }
  throw new Error(`unbalanced braces in ${name}`);
}

function extractStatement(src, re, label) {
  const m = src.match(re);
  assert.ok(m, `${label} not found`);
  return m[0];
}

/** Build a live sandbox out of the real shipped code. */
function loadRenderer(file) {
  const src = readFileSync(file, 'utf8');
  const parts = [
    extractStatement(src, BLOCK_RE, 'COUNTRY NAMES block'),
    extractStatement(src, GEN_BLOCK_RE, 'COUNTRY GENITIVE block'),
    extractStatement(src, /const RESTRICTED_COUNTRY_CODES=\[[^\]]*\];/, 'RESTRICTED_COUNTRY_CODES'),
    ...['countryName', 'hasCountryName', 'countryNameGenitive', 'packageCoverageCodes', 'formatDataLabel', 'publicPackageName', 'countryCode']
      .map((name) => extractFunction(src, name)),
  ];
  return new Function(`${parts.join('\n')}
    return { countryNames, countryNamesGenitive, countryName, hasCountryName, countryNameGenitive, packageCoverageCodes, publicPackageName, countryCode };`)();
}

const RENDERERS = Object.fromEntries(Object.entries(SOURCES).map(([k, v]) => [k, loadRenderer(v)]));
const CATALOG = JSON.parse(readFileSync(CATALOGUE, 'utf8'));
const PACKAGES = Array.isArray(CATALOG) ? CATALOG : CATALOG.packages || CATALOG.data;

// ---------------------------------------------------------------------------
// The generated dictionary is the single source of truth
// ---------------------------------------------------------------------------

test('the shipped storefront copy carries the generated dictionary, and the home none', () => {
  const [a] = Object.values(SOURCES).map((f) => readFileSync(f, 'utf8').match(BLOCK_RE)[0]);
  assert.ok(!BLOCK_RE.test(readFileSync(join(ROOT, 'index.html'), 'utf8')), 'the home must not carry a second copy');
  assert.match(a, /GENERATED by seo\/build-country-dictionary\.mjs/,
    'the block must announce that it is generated, or someone will edit it by hand again');
});

test('the shipped dictionary is what the generator produces right now', () => {
  // Equivalent to `node seo/build-country-dictionary.mjs --check`, asserted here
  // so a stale copy fails the test run and not only CI.
  const dict = buildDictionary();
  for (const [label, r] of Object.entries(RENDERERS)) {
    assert.deepEqual(r.countryNames, dict, `${label} is stale — run the generator`);
  }
});

test('the storefront wording that already shipped is not silently reworded', () => {
  // Five names differ between the SEO source and what customers have been
  // seeing. Overriding them is a decision; losing them would be an accident.
  for (const [code, expected] of Object.entries(STOREFRONT_WORDING)) {
    for (const [label, r] of Object.entries(RENDERERS)) {
      assert.equal(r.countryName(code), expected, `${label} reworded ${code}`);
    }
  }
  assert.equal(SEO_NAMES.CF.ru, 'ЦАР', 'the SEO source is unchanged — only the storefront override differs');
});

// ---------------------------------------------------------------------------
// Brunei — the reported defect
// ---------------------------------------------------------------------------

const BRUNEI = {
  package_id: 'test-bn', name: 'Brunei Darussalam 10GB 30Days',
  data_gb: 10, validity_days: 30, country_code: 'BN', region: 'BN',
  coverage_country_codes: ['BN'],
};

test('BN resolves to Бруней, not to BN', () => {
  for (const [label, r] of Object.entries(RENDERERS)) {
    assert.equal(r.countryName('BN'), 'Бруней', `${label}`);
    assert.equal(r.hasCountryName('BN'), true, `${label}`);
  }
});

test('the Brunei card is titled "Бруней 10 GB", and the heading matches', () => {
  for (const [label, r] of Object.entries(RENDERERS)) {
    assert.equal(r.publicPackageName(BRUNEI), 'Бруней 10 GB', `${label} card title`);
    // The heading is `Тарифы для ${countryNameGenitive(code)}` at the call site.
    // This line used to pin «Тарифы для Бруней» — the nominative fallback that
    // 169 of 198 country pages shipped with.
    assert.equal(`Тарифы для ${r.countryNameGenitive(r.countryCode(BRUNEI))}`, 'Тарифы для Брунея', `${label} heading`);
  }
});

test('every live Brunei package is named, however many there are', () => {
  // This used to pin the count at exactly three. That was a brittle hold on
  // live data: the daily rollout took Brunei to seven, and a test that fails
  // because the shop gained products is a test that will be silenced rather
  // than read. The claim being defended is «no raw code reaches a customer»,
  // so assert that — and keep a floor so an empty catalogue cannot pass.
  const bn = PACKAGES.filter((p) => (p.coverage_country_codes || []).join() === 'BN');
  assert.ok(bn.length >= 3, `expected Brunei packages in the catalogue, found ${bn.length}`);
  for (const p of bn) {
    for (const r of Object.values(RENDERERS)) {
      const name = r.publicPackageName(p);
      // «Бруней 3 GB» for a volume plan, plain «Бруней» for a daily one — it has
      // no total volume, so the mapper has nothing to append. This used to read
      // /^Бруней / for every row and passed only because data_gb had drifted
      // onto daily rows; the storefront titles those from the shared module
      // («Бруней — 500 МБ в день») and never from this mapper.
      const expected = p.plan_type === 'DAILY' ? /^Бруней$/ : /^Бруней /;
      assert.match(name, expected, `still raw: ${name}`);
    }
  }
});

// ---------------------------------------------------------------------------
// The whole catalogue — the claim is "zero raw codes", so prove it on all of it
// ---------------------------------------------------------------------------

test('every country code in the catalogue has a customer-facing name', () => {
  const codes = new Set();
  for (const p of PACKAGES) {
    for (const c of p.coverage_country_codes || []) codes.add(String(c).toUpperCase());
    if (p.country_code) codes.add(String(p.country_code).toUpperCase());
  }
  const alpha2 = [...codes].filter((c) => /^[A-Z]{2}$/.test(c));
  assert.ok(alpha2.length > 150, `expected a full catalogue, got ${alpha2.length} codes`);

  for (const [label, r] of Object.entries(RENDERERS)) {
    const missing = alpha2.filter((c) => !r.hasCountryName(c));
    assert.deepEqual(missing, [], `${label} cannot name: ${missing.join(', ')}`);
  }
});

test('no card in the catalogue is titled with a bare country code', () => {
  // The actual customer-facing claim, checked against every package rather than
  // a sample: a title must never begin with a two-letter code followed by a
  // number, which is exactly the "BN 10 GB" shape.
  const RAW = /^[A-Z]{2}[\s\-]/;
  for (const [label, r] of Object.entries(RENDERERS)) {
    const bad = PACKAGES
      .map((p) => r.publicPackageName(p))
      .filter((title) => RAW.test(title) && !/^(EU|UK)\b/.test(title));
    assert.deepEqual(bad, [], `${label}: ${bad.length} raw-code titles, e.g. ${bad.slice(0, 5).join(' | ')}`);
  }
});

test('every card title is non-empty and carries no UNKNOWN placeholder', () => {
  for (const [label, r] of Object.entries(RENDERERS)) {
    for (const p of PACKAGES) {
      const title = r.publicPackageName(p);
      assert.ok(title.trim().length > 0, `${label}: empty title for ${p.package_id}`);
      assert.doesNotMatch(title, /undefined|null|UNKNOWN|NaN|Другое/, `${label}: ${title}`);
    }
  }
});

