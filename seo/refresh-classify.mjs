// ---------------------------------------------------------------------------
// seo/refresh-classify.mjs — почему упал прогон пересборки: из-за ДАННЫХ или
// из-за КОДА?
//
// ЗАЧЕМ. `.github/workflows/seo-refresh-pr.yml` обращается с любой остановкой
// одинаково: джоб умирает, ветка не трогается, PR не появляется. А PR — это
// единственный канал, которым автоматика разговаривает с человеком, и
// «Сводка изменений» стоит ПОСЛЕ проверок, поэтому при красном гейте не
// появляется и она. Наружу выходит голый красный крестик, и `workflow_run`
// повторяет его до шести раз в сутки.
//
// 2026-09-18 это стоило двух прогонов: поставщик переоценил дневное семейство
// Израиля, у «Israel 500MB/Day» трёхдневная ступень упала 1200 → 450 при ставке
// 450 ₽/день, числа совпали, и утверждение-прокси в гейте не смогло отличить
// «взято из лестницы» от «свалилось на ставку». Снаружи это выглядело ровно так
// же, как сломанный генератор.
//
// ЧЕМ ОНИ РАЗЛИЧИМЫ. Не текстом ошибки — по нему как раз не отличить. Различимы
// двумя фактами, которые известны без догадок:
//
//   1. КАКОЙ ШАГ упал. Генератор, аллоулист, воспроизводимость, работа с
//      веткой — у каждого своя природа, и данные тут ни при чём.
//   2. ЧТО ИЗМЕНИЛОСЬ НА ВХОДЕ с последнего УСПЕШНОГО прогона. Если
//      единственный сдвинувшийся файл — `assets/catalog.json`, то красный гейт
//      может быть только про данные: код ровно тот же, что проходил.
//
// Окно считается от последнего успеха, а не от предыдущего коммита, и это
// принципиально: если человек сломал гейт кодом, а следом бот дважды обновил
// каталог, окно «от прошлого коммита» покажет только каталог и соврёт «данные».
//
// НЕИЗВЕСТНОСТЬ ЧИТАЕТСЯ КАК КОД, И ЭТО ЕДИНСТВЕННОЕ ВЕРНОЕ НАПРАВЛЕНИЕ.
// «Данные» звучат как «это не мы, это поставщик» и снимают срочность. Назвать
// дефект кода данными — дорогая ошибка; назвать движение каталога кодом —
// дешёвая. Поэтому всё, чего мы не смогли установить, попадает в CODE или
// UNKNOWN, и ни одна ветка не возвращает DATA по умолчанию.
// ---------------------------------------------------------------------------

/** Единственный путь, движение которого само по себе не является изменением кода. */
export const DATA_INPUT = 'assets/catalog.json';

export const KIND = Object.freeze({
  DATA: 'data',             // поставщик сказал то, чего страницы говорить не вправе
  CODE: 'code',             // сломан генератор, гейт или их предпосылка
  AUTOMATION: 'automation', // ветка, аллоулист, лиза, окружение прогона
  UNKNOWN: 'unknown',       // не установили — обращаемся как с кодом
});

// Шаги, падение которых не зависит от содержимого каталога ни при каком раскладе.
const BY_STEP = Object.freeze({
  'Пересборка':                    { kind: KIND.CODE,       why: 'генератор упал при сборке' },
  'Воспроизводимость':             { kind: KIND.CODE,       why: 'повторная сборка дала другой результат' },
  'Только ожидаемые файлы':        { kind: KIND.AUTOMATION, why: 'генератор записал файл вне аллоулиста' },
  'Проверки — установка браузера': { kind: KIND.AUTOMATION, why: 'окружение прогона: npm ci или установка Chromium' },
  'Ветка':                         { kind: KIND.AUTOMATION, why: 'ветка: чужой коммит, лиза или push' },
  'Pull request':                  { kind: KIND.AUTOMATION, why: 'создание или обновление pull request' },
  'Сводка изменений':              { kind: KIND.CODE,       why: 'сборка сводки' },
  'Снимок артефактов до пересборки': { kind: KIND.AUTOMATION, why: 'снимок артефактов до сборки' },
  'Есть ли что публиковать':       { kind: KIND.AUTOMATION, why: 'определение наличия изменений' },
});

// Шаги, где вопрос «данные или код» вообще осмыслен: они читают каталог.
const GATE_STEPS = Object.freeze(['Проверки — гейты витрины', 'Проверки — браузер']);

/**
 * @param {object} o
 * @param {string} o.failedStep   имя упавшего шага, как в workflow
 * @param {string[]|null} o.inputsChanged  пути, изменившиеся с последнего успеха;
 *        null — окно установить не удалось (нет успешных прогонов, API не ответил)
 * @returns {{kind: string, why: string, headline: string}}
 */
export function classifyFailure({ failedStep, inputsChanged } = {}) {
  const step = typeof failedStep === 'string' ? failedStep.trim() : '';
  if (!step) {
    return { kind: KIND.UNKNOWN, why: 'не удалось определить упавший шаг',
             headline: 'Класс не установлен — разбирать как код' };
  }

  if (!GATE_STEPS.includes(step)) {
    const known = BY_STEP[step];
    if (known) return { ...known, headline: headlineFor(known.kind, step) };
    return { kind: KIND.UNKNOWN, why: `шаг «${step}» не описан в классификаторе`,
             headline: 'Класс не установлен — разбирать как код' };
  }

  // Ниже — только гейты. Здесь и только здесь решает окно входов.
  if (!Array.isArray(inputsChanged)) {
    return { kind: KIND.UNKNOWN, why: 'не удалось выяснить, что изменилось с последнего успешного прогона',
             headline: 'Класс не установлен — разбирать как код' };
  }

  const paths = inputsChanged.map((p) => String(p).trim()).filter(Boolean);
  const nonData = paths.filter((p) => p !== DATA_INPUT);

  if (!paths.length) {
    // Гейт покраснел, хотя с последнего успеха не изменилось НИЧЕГО. Это не
    // данные: это недетерминированность или что-то снаружи репозитория.
    return { kind: KIND.CODE, why: 'с последнего успешного прогона не изменилось ничего, а гейт покраснел — прогон недетерминирован',
             headline: 'Код: гейт краснеет без единого изменения на входе' };
  }
  if (!nonData.length) {
    return { kind: KIND.DATA, why: `с последнего успешного прогона изменился только ${DATA_INPUT}`,
             headline: 'Данные: сдвинулся каталог поставщика, код тот же' };
  }
  const alsoData = paths.length !== nonData.length;
  return {
    kind: KIND.CODE,
    why: `с последнего успешного прогона изменился код: ${nonData.slice(0, 8).join(', ')}`
       + (nonData.length > 8 ? ` и ещё ${nonData.length - 8}` : '')
       + (alsoData ? `; каталог тоже двигался, поэтому «только данные» исключено` : ''),
    headline: alsoData ? 'Код (каталог двигался тоже) — разбирать с кода' : 'Код: изменились файлы репозитория',
  };
}

function headlineFor(kind, step) {
  if (kind === KIND.CODE) return `Код: упал шаг «${step}»`;
  if (kind === KIND.AUTOMATION) return `Автоматика: упал шаг «${step}»`;
  return `Класс не установлен — шаг «${step}»`;
}
