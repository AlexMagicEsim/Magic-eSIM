/* =====================================================================
 * build-country-dictionary-locale — the country names, for the browser, in
 * every language that has its own prefix.
 * ---------------------------------------------------------------------
 * I18N-08c. This was build-country-dictionary-en.mjs, English only. The names
 * now come from `countryName(iso, lang)` (seo/country-names-i18n.mjs), which
 * serves all seven languages from ONE list of codes: ru/en from
 * seo/country-names.mjs, the five others from the CLDR table of I18N-03.
 *
 * One file per published prefixed language, at /assets/country-names-<prefix>.js,
 * exposing window.MagicCountryNames<Prefix> (En, Es, Zh, …) — the page's
 * scripts pick theirs from the page language (en/country.js). English is
 * byte-for-byte the file it always was, and keeps its entry point
 * (seo/build-country-dictionary-en.mjs).
 *
 * IT WRITES ONLY PUBLISHED LANGUAGES. A language that is not enabled for the
 * site gets no file — a file under /assets/ is a public URL. `renderNames()`
 * renders any planned language in memory (the rehearsal test uses it).
 *
 *   node seo/build-country-dictionary-locale.mjs
 *
 * seo/test-country-names-en.mjs and seo/test-locale-rehearsal.mjs fail if a
 * committed file and this generator disagree.
 * ================================================================== */
import { writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { COUNTRY_NAMES } from './country-names.mjs';
import { countryName } from './country-names-i18n.mjs';
import { LOCALES, locale } from './locales.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** «En», «Es», «Zh»: the part of a browser global that names the language. */
export const globalSuffix = (prefix) => String(prefix).charAt(0).toUpperCase() + String(prefix).slice(1);

/** Where a language's names live and what they are called — for the generators and the tests. */
export function namesFile(code) {
  const L = locale(code);
  if (!L || !L.prefix) throw new Error(`country names: ${String(code)} has no prefixed site`);
  return Object.freeze({
    rel: `assets/country-names-${L.prefix}.js`,
    src: `/assets/country-names-${L.prefix}.js`,
    global: `MagicCountryNames${globalSuffix(L.prefix)}`,
  });
}

/* The entry point named in a file's header: a language-specific one when the
 * repository has it (English, for history), else this generator. */
function entryPoint(L) {
  const own = `seo/build-country-dictionary-${L.prefix}.mjs`;
  return existsSync(join(ROOT, own)) ? own : 'seo/build-country-dictionary-locale.mjs';
}

/* «English», «Spanish», «Simplified Chinese» — for a comment only. */
const languageName = (code) => new Intl.DisplayNames(['en'], { type: 'language' }).of(code);

/** The file for one language, as text. Any planned prefixed language; nothing is written. */
export function renderNames(code) {
  const L = locale(code);
  const F = namesFile(code);
  const entries = Object.keys(COUNTRY_NAMES).sort().map((iso) => {
    const name = String(countryName(iso, L.code) || '').replace(/\\/g, '\\\\').replace(/'/g, "\\'");
    return `  ${iso}: '${name}'`;
  }).join(',\n');
  const gen = entryPoint(L);

  return `/* GENERATED by ${gen} — do not edit by hand.
 * Source of truth: seo/country-names.mjs. Regenerate with
 *   node ${gen}
 * seo/test-country-names-en.mjs fails when this file and the source disagree.
 */
(function (root) {
  'use strict';
  var NAMES = {
${entries}
  };
  root.${F.global} = {
    /** ISO -> ${languageName(L.code)} name, or the ISO code itself when we have no name. */
    of: function (iso) {
      var k = String(iso || '').toUpperCase();
      return Object.prototype.hasOwnProperty.call(NAMES, k) ? NAMES[k] : k;
    },
    /* A COPY. Returning the internal object let a caller rewrite a country's
       name at runtime, which is the kind of thing that is only ever noticed
       long after it happens. */
    all: function () {
      var out = {};
      for (var k in NAMES) if (Object.prototype.hasOwnProperty.call(NAMES, k)) out[k] = NAMES[k];
      return out;
    }
  };
  if (typeof module === 'object' && module.exports) module.exports = root.${F.global};
})(typeof window !== 'undefined' ? window : globalThis);
`;
}

/** The languages that get a file: enabled for the site, with a prefix. */
export function publishedNameLocales(list = LOCALES) {
  return list.filter((l) => l.prefix && l.site.enabled).map((l) => l.code);
}

/** Write one published language's file. Refuses an unpublished one. */
export function writeNames(code) {
  if (!publishedNameLocales().includes(code)) throw new Error(`country names: ${String(code)} is not published — refusing to write it`);
  const F = namesFile(code);
  writeFileSync(join(ROOT, F.rel), renderNames(code), 'utf8');
  return F;
}

// Compared as PATHS, not as URL strings: the repository lives under a directory
// with a space, which import.meta.url percent-encodes.
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  for (const code of publishedNameLocales()) {
    const F = writeNames(code);
    console.log(`country-names (${code}): ${Object.keys(COUNTRY_NAMES).length} names -> ${F.rel}`);
  }
}
