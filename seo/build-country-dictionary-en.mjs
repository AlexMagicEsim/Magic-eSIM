/* =====================================================================
 * build-country-dictionary-en — the English country names, for the browser.
 * ---------------------------------------------------------------------
 * GENERATED from seo/country-names.mjs, which is the single source of truth
 * for a country's Russian name, its English name and its slug. The Russian
 * half already reaches the browser this way (build-country-dictionary.mjs
 * rewrites index.html and assets/country-tariffs.js); this does the same for
 * the English half so that `/en/` cannot drift from the dictionary the SEO
 * pipeline uses.
 *
 * Writing it by hand was the alternative, and a hand-written copy of 234 names
 * is a copy that is wrong about one of them within a month.
 *
 *   node seo/build-country-dictionary-en.mjs
 *
 * `seo/test-country-names-en.mjs` fails if the committed file and this
 * generator disagree, so the check is not «somebody remembered to run it».
 * ================================================================== */
import { writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { COUNTRY_NAMES } from './country-names.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(ROOT, 'assets', 'country-names-en.js');

export function render() {
  const entries = Object.keys(COUNTRY_NAMES).sort().map((iso) => {
    const en = String(COUNTRY_NAMES[iso].en || '').replace(/'/g, "\\'");
    return `  ${iso}: '${en}'`;
  }).join(',\n');

  return `/* GENERATED by seo/build-country-dictionary-en.mjs — do not edit by hand.
 * Source of truth: seo/country-names.mjs. Regenerate with
 *   node seo/build-country-dictionary-en.mjs
 * seo/test-country-names-en.mjs fails when this file and the source disagree.
 */
(function (root) {
  'use strict';
  var NAMES = {
${entries}
  };
  root.MagicCountryNamesEn = {
    /** ISO -> English name, or the ISO code itself when we have no name. */
    of: function (iso) {
      var k = String(iso || '').toUpperCase();
      return Object.prototype.hasOwnProperty.call(NAMES, k) ? NAMES[k] : k;
    },
    /* A COPY. Returning the internal object let a caller rewrite a country's
       name at runtime, which is the kind of thing that is only ever noticed
       long after it happens. */
    all: function () {
      var out = {};
      for (var k in NAMES) if (Object.prototype.hasOwnProperty.call(NAMES, k)) out[k] = NAMES[k];
      return out;
    }
  };
  if (typeof module === 'object' && module.exports) module.exports = root.MagicCountryNamesEn;
})(typeof window !== 'undefined' ? window : globalThis);
`;
}

// Compared as PATHS, not as URL strings. This repository lives under
// «Magic eSIM Site» — a directory with a space — and `import.meta.url`
// percent-encodes it, so the usual `file://${process.argv[1]}` comparison is
// false here and the generator silently does nothing.
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  writeFileSync(OUT, render(), 'utf8');
  console.log(`country-names-en: ${Object.keys(COUNTRY_NAMES).length} names -> ${OUT}`);
}
