// Revenue Attribution: страница → checkout → заказ → выручка → прибыль.
//
// Сейчас цепочка разорвана в первом же звене, и важно понимать где именно.
//
// ЧТО ЕСТЬ СЕГОДНЯ
//   retail_orders.country_code — какая СТРАНА куплена.
//   Поскольку страница на страну ровно одна, выручка НА СТРАНУ считается
//   честно и доступна прямо сейчас. Это уже отвечает на вопрос «какие
//   направления приносят деньги».
//
// ЧЕГО НЕТ
//   Откуда пришёл покупатель. Заказ с country_code=TR мог прийти со страницы
//   /esim/turkey/, с лендинга, из Telegram или по прямой ссылке. Поэтому
//   нельзя сказать «страница Турции заработала N ₽» — можно сказать только
//   «направление Турция заработало N ₽». Разница принципиальная: первое
//   оценивает работу страницы, второе — спрос на страну.
//
// ЦЕПОЧКА, КОТОРУЮ НАДО ЗАМКНУТЬ
//
//   1. Кнопка на странице страны                  [сайт, реализовано ниже]
//        /?country=TR&src=country-page&from=turkey
//   2. Цель Метрики checkout_click с параметром    [сайт, реализовано ниже]
//   3. Лендинг кладёт метку в sessionStorage и
//      передаёт её в создание заказа               [лендинг + бэкенд]
//   4. retail_orders.attribution_page              [миграция, НЕ применена]
//
// Шаги 1–2 сделаны здесь: они ничего не ломают, лендинг игнорирует незнакомые
// параметры, а данные начнут копиться с момента выкладки. Шаги 3–4 требуют
// изменения бэкенда и продакшн-миграции — они подготовлены, но не применены.
//
// Пока шаг 4 не применён, всё, что считает система, помечено
// granularity: 'country' и НЕ выдаётся за атрибуцию страницы.

export const GRANULARITY = Object.freeze({
  COUNTRY: 'country',   // есть сейчас: заказ знает страну
  PAGE: 'page',         // будет после миграции: заказ знает страницу входа
});

/** Ссылка на checkout с меткой происхождения. */
export function buyHref(iso, slug) {
  const code = String(iso || '').toUpperCase();
  const params = new URLSearchParams({ country: code, src: 'country-page', from: slug });
  return `/?${params}#global-pricing`;
}

/**
 * Миграция, замыкающая цепочку. НЕ применена: продакшн-миграции требуют
 * отдельного подтверждения.
 *
 * Колонки nullable без значения по умолчанию — заказ без метки честно
 * остаётся без метки, а не приписывается странице, которой не было.
 */
export const MIGRATION_SQL = `-- 2026-08-attribution-page.sql  (НЕ ПРИМЕНЕНА)
-- Замыкает цепочку страница → checkout → заказ.
--
-- Все колонки nullable: заказ, пришедший не со страницы страны, должен
-- остаться БЕЗ метки. Значение по умолчанию здесь приписало бы выручку
-- странице, которую покупатель не открывал.

alter table retail_orders
  add column if not exists attribution_source text,        -- 'country-page' | 'landing' | 'direct' | ...
  add column if not exists attribution_page   text,        -- slug страницы входа
  add column if not exists attribution_seen_at timestamptz; -- когда метка поставлена

create index if not exists retail_orders_attribution_page_idx
  on retail_orders (attribution_page)
  where attribution_page is not null;

-- Метка ставится один раз, при первом заходе, и не переписывается последующими
-- переходами: иначе последний клик съест всю заслугу первого.
`;

/**
 * Скрипт для страниц: ставит цель в Метрике и запоминает происхождение.
 * Вставляется в сгенерированные страницы; ничего не требует от бэкенда.
 */
/**
 * Скрипт для страниц страны.
 *
 * Ставит ТОЛЬКО метку происхождения. Цель в Метрику здесь не отправляется
 * намеренно: country-tariffs.js уже шлёт `country_tariff_click` и
 * `tariff_buy_click` с country_code, и Метрика умеет разложить достижение цели
 * по URL. Вторая цель на то же действие дала бы двойной счёт кликов и
 * расхождение между отчётом Метрики и панелью.
 *
 * Чего в Метрике действительно нет — это СТРАНИЦЫ ВХОДА в самом заказе. Её и
 * кладём: sessionStorage переживает переход на лендинг, а первый заход не
 * переписывается последующими, чтобы последний клик не забрал заслугу.
 */
export const CLIENT_SNIPPET = `
<script>
/* Attribution: запоминаем, что визит начался со страницы страны.
   Цель в Метрику НЕ шлём — country_tariff_click уже отправляется
   country-tariffs.js, и вторая цель на тот же клик удвоила бы счёт. */
(function(){
  try {
    if (sessionStorage.getItem('mesim_attr')) return;
    var slug = location.pathname.split('/').filter(Boolean).pop() || '';
    if (!slug) return;
    sessionStorage.setItem('mesim_attr', JSON.stringify({
      source: 'country-page', page: slug, at: new Date().toISOString()
    }));
  } catch (e) { /* приватный режим — метки просто не будет */ }
})();
</script>`;

