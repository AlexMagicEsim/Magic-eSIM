#!/usr/bin/env node
/**
 * Generates the nginx redirect rules of magicesim.store from THE ONE URL MAP (seo/url-migration.mjs) and the list of
 * country pages (seo/catalogue-countries.json). Nothing else may type a redirect: infra/web/nginx/site.conf includes
 * the two files written here, and infra/web/ holds no other `return 301` / `rewrite` than its fixed host redirects.
 *
 *   infra/web/nginx/redirects.conf     server context: one `location` per rule of RULES
 *   infra/web/nginx/country-map.conf   http context:   `/?country=XX` -> /ru/esim/<slug>/, the other query kept
 *
 * PRECEDENCE. newPath() takes the FIRST rule that matches, in order. nginx takes an `=` location before any prefix,
 * and among `^~` prefixes the LONGEST one — never the first. The two agree only when no exact rule's path is caught by
 * an earlier prefix and no prefix shadows a longer, later one. nginxNewPath() models nginx's choice, and the build
 * REFUSES (throws) when it disagrees with newPath() on any probe — every rule's own path, a path under every prefix,
 * every sitemap URL — so a map edit that nginx could not reproduce fails here instead of on the server.
 *
 *   node scripts/build-web-server-config.mjs           write both files
 *   node scripts/build-web-server-config.mjs --check   exit 1 when a committed file differs from a fresh generation
 *
 * Exit codes: 0 written / up to date; 1 stale (--check) or the map cannot be expressed in nginx.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { RULES, STAYS, newPath, countryQueryTargets, withDirSlash } from '../seo/url-migration.mjs';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT_DIR = join(REPO, 'infra', 'web', 'nginx');
export const REDIRECTS_FILE = 'redirects.conf';
export const COUNTRY_MAP_FILE = 'country-map.conf';

const HEADER = (what) => [
  '# GENERATED by scripts/build-web-server-config.mjs from seo/url-migration.mjs and seo/catalogue-countries.json.',
  '# DO NOT EDIT BY HAND: change the map and regenerate (`node scripts/build-web-server-config.mjs`);',
  '# `npm test` fails while this file differs from a fresh generation (seo/test-web-server-config.mjs).',
  `# ${what}`,
  '',
];

/** A path nginx can carry literally in a location and a rewrite: no space, quote, brace, semicolon, `$` or regex trap. */
const SAFE_PATH = /^\/[A-Za-z0-9._~\/-]*$/;

/** nginx's choice for `path` over the generated locations: `=` first, else the longest `^~` prefix, else none. */
export function nginxNewPath(path, rules = RULES) {
  const exact = rules.find((r) => r.type === 'exact' && r.from === path);
  if (exact) return exact.to;
  let best = null;
  for (const r of rules) if (r.type === 'prefix' && path.startsWith(r.from) && (!best || r.from.length > best.from.length)) best = r;
  return best ? best.to + withDirSlash(path.slice(best.from.length)) : null;
}

export function sitemapPaths(root = REPO) {
  return [...readFileSync(join(root, 'sitemap.xml'), 'utf8').matchAll(/<loc>\s*([^<\s]+)\s*<\/loc>/g)]
    .map((m) => m[1].replace(/^https:\/\/magicesim\.store/, '') || '/');
}

/** The probes the equivalence check runs on: every rule's path and paths under it, every STAYS path, the sitemap. */
export function probePaths(rules = RULES, extra = []) {
  const out = new Set(['/', ...STAYS, ...extra]);
  for (const r of rules) {
    out.add(r.from);
    if (r.from.endsWith('/')) { out.add(`${r.from}x/`); out.add(`${r.from}x`); out.add(`${r.from}a/b`); out.add(`${r.from}a/b.html`); out.add(r.from.slice(0, -1)); }
    else { out.add(`${r.from}/`); out.add(`${r.from}x`); }
    out.add(r.to);
  }
  return [...out];
}

/** Refuses a map nginx cannot reproduce. Returns the list of disagreements (empty = equivalent). */
export function disagreements(rules = RULES, paths = probePaths(rules), pick = newPath) {
  return paths.map((p) => [p, pick(p), nginxNewPath(p, rules)]).filter(([, a, b]) => a !== b)
    .map(([p, a, b]) => `${p}: newPath -> ${a}, nginx -> ${b}`);
}

function validate(rules) {
  const seen = new Set();
  for (const r of rules) {
    if (!['exact', 'prefix'].includes(r.type)) throw new Error(`url map: unknown rule type ${r.type}`);
    for (const p of [r.from, r.to]) if (!SAFE_PATH.test(p)) throw new Error(`url map: not a plain path: ${p}`);
    if (r.from === '/') throw new Error('url map: / is a page (and the /?country= router), never a rule');
    if (r.type === 'prefix' && !r.from.endsWith('/')) throw new Error(`url map: a prefix rule ends with a slash: ${r.from}`);
    if (r.type === 'prefix' && !r.to.endsWith('/')) throw new Error(`url map: a prefix target ends with a slash: ${r.to}`);
    const key = `${r.type} ${r.from}`;
    if (seen.has(key)) throw new Error(`url map: duplicate ${key} (nginx refuses a duplicate location)`);
    seen.add(key);
  }
}

const reEscape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

export function redirectsConf(rules = RULES, sitemap = sitemapPaths()) {
  validate(rules);
  const bad = disagreements(rules, probePaths(rules, sitemap));
  if (bad.length) throw new Error(`url map: nginx precedence would differ from newPath():\n  ${bad.join('\n  ')}`);
  const lines = HEADER('Server context: included by infra/web/nginx/site.conf inside the apex TLS server.');
  lines.push('# `=` keeps the query with $is_args$args; a `rewrite ... permanent` appends the original query itself.', '');
  for (const r of rules) {
    if (r.type === 'exact') lines.push(`location = ${r.from} { return 301 ${r.to}$is_args$args; }`);
    else {
      // A last segment without a dot and without its slash gets the slash here (withDirSlash), in the same 301.
      lines.push(`location ^~ ${r.from} {`,
        `    rewrite ^${reEscape(r.from)}((?:[^/]*/)*[^/.]+)$ ${r.to}$1/ permanent;`,
        `    rewrite ^${reEscape(r.from)}(.*)$ ${r.to}$1 permanent;`,
        '}');
    }
  }
  return `${lines.join('\n')}\n`;
}

export function countryMapConf(countries) {
  const targets = countryQueryTargets(countries);
  const codes = Object.keys(targets).sort();
  if (!codes.length) throw new Error('country map: no country with a page — refusing an empty map');
  const lines = HEADER('http context: /?country=XX (the old Russian home\'s deep link) -> the Russian country page.');
  lines.push(
    '# Codes exactly as seo/catalogue-countries.json; anything else maps to "" and location = / serves the page with',
    '# 200. The value is a plain path from the generated list, never from the URL. nginx compares map STRINGS',
    '# case-insensitively, so ?country=tr reaches the same page as ?country=TR, like the old home\'s script.',
    'map $arg_country $country_code {',
    '    default "";',
    '    "~*^[A-Z]{2}$" $arg_country;',
    '}',
    'map $country_code $country_redirect {',
    '    default "";',
  );
  for (const c of codes) lines.push(`    ${c} ${targets[c]};`);
  lines.push(
    '}',
    '',
    '# The rest of the query (UTM and the like) without the first `country` parameter, kept on the redirect.',
    'map $args $country_rest {',
    '    default "";',
    '    "~^country=[^&]*(?:&(?<after>.*))?$" $after;',
    '    "~^(?<before>.*?)&country=[^&]*(?<tail>&.*)?$" $before$tail;',
    '}',
    'map $country_rest $country_rest_q {',
    '    "" "";',
    '    default ?$country_rest;',
    '}',
  );
  return `${lines.join('\n')}\n`;
}

export function generate(root = REPO) {
  const countries = JSON.parse(readFileSync(join(root, 'seo', 'catalogue-countries.json'), 'utf8')).countries;
  return {
    [REDIRECTS_FILE]: redirectsConf(RULES, sitemapPaths(root)),
    [COUNTRY_MAP_FILE]: countryMapConf(countries),
  };
}

/** Files whose committed text differs from a fresh generation. */
export function staleFiles(root = REPO, dir = OUT_DIR) {
  const fresh = generate(root);
  return Object.keys(fresh).filter((f) => !existsSync(join(dir, f)) || readFileSync(join(dir, f), 'utf8') !== fresh[f]);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.includes('--check')) {
      const stale = staleFiles();
      if (stale.length) {
        console.error(`stale generated web-server config: ${stale.join(', ')} — run node scripts/build-web-server-config.mjs`);
        process.exit(1);
      }
      console.log('web-server config is up to date');
    } else {
      mkdirSync(OUT_DIR, { recursive: true });
      for (const [f, text] of Object.entries(generate())) writeFileSync(join(OUT_DIR, f), text);
      console.log(`wrote infra/web/nginx/${REDIRECTS_FILE} (${RULES.length} rules), infra/web/nginx/${COUNTRY_MAP_FILE}`);
    }
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
