/**
 * The terms a per-day plan is sold for, priced BY THE SERVER.
 *
 * Returns [] when the ladder is missing, and the screen then offers no
 * purchase at all — a term we cannot price is a term we cannot sell, and
 * guessing one here would be the browser deciding what someone pays.
 */
function dailyTerms(pkg) {
  const list = Array.isArray(pkg && pkg.term_prices) ? pkg.term_prices : [];
  return list
    .filter((t) => t && Number(t.days) > 0 && Number(t.price) > 0)
    .map((t) => ({ days: Number(t.days), price: Number(t.price) }));
}

/**
 * The cheapest price this package can ACTUALLY be bought at — or null when it
 * cannot be bought at all.
 *
 * WHY THIS EXISTS. The country card's «от X ₽» used to be `min(item.price)`
 * over every package. For a PER_DAY plan `price` is the rate for ONE DAY, and
 * no such plan is sold for one day — the shortest term is three. So Turkey
 * advertised «от 100 ₽» while the cheapest thing anyone could put in a basket
 * cost 200 ₽. Sixteen of sixteen popular countries were wrong, and 183 of 196
 * across the catalogue.
 *
 * The ladder is read through `dailyTerms`, the same function the country screen
 * and the tariff card already use, so the card and the screen can never again
 * disagree about what a plan costs — there is one reader of `term_prices`, not
 * two.
 *
 * The three cases, and why each is what it is:
 *   - DAILY with a priced ladder  -> the cheapest term in the ladder. This is
 *     the number the buyer sees when the plan opens.
 *   - DAILY, mode PER_DAY, no ladder -> null. `dailyCard` shows «—» and
 *     refuses to open such a plan, so it is not on sale and must not set a
 *     price the card promises. Zero rows today; the branch is here so a future
 *     data defect degrades to "no price" rather than back to "a lie".
 *   - anything else (FIXED_TERM daily, FIXED_VOLUME) -> `price`, which for
 *     those IS the whole-purchase price.
 */
function sellableFrom(pkg) {
  if (!pkg || typeof pkg !== 'object') return null;

  if (String(pkg.plan_type || '') === 'DAILY') {
    const terms = dailyTerms(pkg);
    if (terms.length) return Math.min(...terms.map((t) => t.price));
    if (String(pkg.daily_term_mode || '') === 'PER_DAY') return null;
  }

  const n = Number(pkg.price);
  return Number.isFinite(n) && n > 0 ? n : null;
}

/**
 * The «от» for a group of packages: the cheapest one anybody can buy.
 *
 * Deliberately NOT `items[0].price` after the sort. The sort orders the list
 * the screen renders and is left alone; the price shown on the card is a
 * different question, and answering it from the sort is what tied the two
 * together and produced the wrong number.
 */
function groupFrom(items) {
  const prices = (Array.isArray(items) ? items : [])
    .map(sellableFrom)
    .filter((n) => n !== null);
  return prices.length ? Math.min(...prices) : null;
}

/**
 * What makes two purchases the same intent.
 *
 * ONE builder, used by both the mint and the clear. They were separate copies
 * of the same five lines, which is fine right up until one of them grows a
 * sixth: a scope that disagrees hashes to a different slot, so minting would
 * store a key that clearing could never find — and the stale key would be
 * reused by a later, different purchase.
 *
 * `days` is that sixth line. Two terms of one daily tariff are two different
 * orders for two different amounts; without it, choosing 30 days after 7 would
 * reuse the first intent's key and the backend would correctly return the
 * FIRST order — a customer charged for a week and shown a month.
 */
function purchaseIntentScope(intent) {
  return [
    'buy',
    String((intent && intent.package_id) || ''),
    String((intent && intent.payment_type) || ''),
    String((intent && intent.promo_code) || '').trim().toUpperCase(),
    String((intent && intent.email) || '').trim().toLowerCase(),
    String((intent && intent.days) || ''),
  ].join('|');
}

function purchaseIntentKey(intent, storage, randomHex) {
  const scope = purchaseIntentScope(intent);

  const slot = `mesim.idem.${hash32(scope)}`;
  const existing = storage && storage.getItem ? storage.getItem(slot) : null;
  if (existing) return existing;

  const fresh = `tma-${hash32(scope)}-${randomHex(8)}`;
  if (storage && storage.setItem) storage.setItem(slot, fresh);

  return fresh;
}

/** Forget an intent's key, so the next purchase of the same tariff is a new one. */
function clearIntentKey(intent, storage) {
  const scope = purchaseIntentScope(intent);
  if (storage && storage.removeItem) storage.removeItem(`mesim.idem.${hash32(scope)}`);
}

/** Tiny stable hash. Not security — a storage slot name. */
function hash32(text) {
  let h = 2166136261;
  const s = String(text);
  for (let i = 0; i < s.length; i += 1) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }

  return (h >>> 0).toString(36);
}

/* --------------------------------------------------------------------------
 * The API client
 * ----------------------------------------------------------------------- */

class ApiError extends Error {
  constructor(status, code, message, body) {
    super(message || code || `HTTP ${status}`);
    this.name = 'ApiError';
    this.status = status;
    this.code = code || '';
    this.body = body || null;
  }

  /** The session is gone and the app must mint a new one from initData. */
  get isAuthFailure() {
    return this.status === 401;
  }

  /**
   * The request never reached a decision — a gateway drop, a timeout, an offline
   * radio. Safe to retry for a read; for a write, only with a key.
   */
  get isTransport() {
    return this.status === 0 || this.status === 502 || this.status === 503 || this.status === 504;
  }
}

/**
 * @param {object} deps
 * @param {Function} deps.fetch      window.fetch, or a stub
 * @param {object}   deps.storage    sessionStorage-like
 * @param {Function} [deps.now]
 * @param {Function} [deps.sleep]
 * @param {Function} [deps.randomHex]
 */
function createApi(deps = {}) {
  const doFetch = deps.fetch;
  const storage = deps.storage || memoryStorage();
  const now = deps.now || (() => Date.now());
  const wait = deps.sleep || sleep;
  const randomHex = deps.randomHex || defaultRandomHex;
  // A single `base` still works (the storefront passes one); otherwise the
  // ordered endpoint list drives failover.
  const endpoints = deps.endpoints
    || (deps.base ? [{ name: 'custom', base: deps.base }] : API_ENDPOINTS);
  const telemetry = typeof deps.telemetry === 'function' ? deps.telemetry : () => {};

  // Held in memory only. Writing a bearer to localStorage would leave it on the
  // device after the app closes, and it is re-mintable from initData for free.
  let sessionToken = null;
  let sessionExpiresAt = 0;

  async function once(path, { method = 'GET', body = null, auth = true, base = endpoints[0].base } = {}) {
    const controller = typeof AbortController === 'function' ? new AbortController() : null;
    const timer = controller ? setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS) : null;

    try {
      const res = await doFetch(base + path, {
        method,
        headers: Object.assign(
          { 'Content-Type': 'application/json', Accept: 'application/json' },
          auth && sessionToken ? { Authorization: `Bearer ${sessionToken}` } : {}
        ),
        body: body === null ? undefined : JSON.stringify(body),
        signal: controller ? controller.signal : undefined,
      });

      const text = await res.text();
      let json = null;
      try { json = text ? JSON.parse(text) : null; } catch { json = null; }

      if (!res.ok) {
        throw new ApiError(res.status, json && json.error, json && json.message, json);
      }

      return json;
    } catch (err) {
      if (err instanceof ApiError) throw err;
      // A thrown fetch is a transport failure: DNS, TLS, offline, abort. Status 0
      // so `isTransport` treats it like the gateway drop it usually is.
      throw new ApiError(0, 'NETWORK', 'network unavailable', null);
    } finally {
      if (timer) clearTimeout(timer);
    }
  }

  /**
   * One request, with the retry policy the method deserves.
   *
   * A 401 is retried exactly once, after re-authenticating — a 30-minute session
   * expiring while the app sits open is the single most likely failure here, and
   * making the customer notice it would be pointless.
   */
  /**
   * May this failure be carried to the other endpoint?
   *
   * ONLY a transport failure — status 0 (abort, DNS, TLS, offline), 502, 503,
   * 504 — means "this road did not reach a verdict". Everything else is an
   * answer, and an answer must be honoured wherever it came from.
   *
   * This is the whole safety of the design. A 401 re-asked at the other host is
   * still a 401 and merely doubles the delay; a 409 or a 422 re-asked is worse,
   * because the second host may be a moment behind and give a different reply to
   * a question already settled. Both endpoints are the same database — asking it
   * twice does not make the answer truer.
   */
  function shouldFailOver(err) {
    return Boolean(err && err.isTransport);
  }

  /**
   * One logical request, across the endpoint list.
   *
   * Bounded twice over: each endpoint gets its own small attempt budget, and
   * there are exactly two endpoints. Worst case is attempts×endpoints requests
   * and then a thrown error — never a loop that keeps a customer waiting on a
   * network that is not coming back.
   */
  async function request(path, opts = {}) {
    const isWrite = opts.method && opts.method !== 'GET';
    const retryable = !isWrite || Boolean(opts.idempotent);
    const attempts = isWrite
      ? (opts.idempotent ? WRITE_ATTEMPTS_WITH_KEY : 1)
      : READ_ATTEMPTS;
    const backoff = isWrite ? WRITE_BACKOFF_MS : READ_BACKOFF_MS;

    let lastError = null;
    let reauthed = false;
    let primaryMs = null;

    for (let e = 0; e < endpoints.length; e += 1) {
      const endpoint = endpoints[e];
      const startedAt = now();

      for (let attempt = 0; attempt < attempts; attempt += 1) {
        try {
          const out = await once(path, { ...opts, base: endpoint.base });
          telemetry({
            api_route: endpoint.name,
            path,
            primary_latency_ms: primaryMs,
            latency_ms: now() - startedAt,
            fallback_used: e > 0,
            fallback_reason: e > 0 ? (lastError && (lastError.code || `http_${lastError.status}`)) : null,
          });

          return out;
        } catch (err) {
          lastError = err;

          if (err.isAuthFailure && !reauthed && opts.auth !== false && deps.reauthenticate) {
            reauthed = true;
            await deps.reauthenticate();
            continue;                      // does not consume an attempt
          }

          // An answer, not an outage: stop everywhere, not just here.
          if (!shouldFailOver(err)) {
            telemetry({
              api_route: endpoint.name,
              path,
              primary_latency_ms: primaryMs,
              latency_ms: now() - startedAt,
              fallback_used: e > 0,
              fallback_reason: null,
              refused: err.status || 0,
            });
            throw err;
          }

          // A write with no key may not be repeated anywhere — not on this
          // endpoint and not on the other one. It may already have been applied.
          if (!retryable) throw err;

          if (attempt < attempts - 1) await wait(backoff[Math.min(attempt, backoff.length - 1)]);
        }
      }

      if (e === 0) primaryMs = now() - startedAt;
    }

    telemetry({
      api_route: 'none',
      path,
      primary_latency_ms: primaryMs,
      fallback_used: endpoints.length > 1,
      fallback_reason: lastError && (lastError.code || `http_${lastError.status}`),
      failed: true,
    });

    throw lastError;
  }

  /* ---- session ---- */

  /**
   * Mint a session from initData.
   *
   * This is the one request the entire app waits on, and until 2026-08-17 it was
   * the only one in the file with no retry at all — `once`, one shot. A cold
   * gateway (TD-55) answers the first call after an idle period with a 502 about
   * twelve seconds in; measured 2026-08-17, five of six cold probes did exactly
   * that while the same instance then served 401s in 0.2s. One such 502 killed
   * the Mini App outright: no session, no catalogue, nothing to tap (R-44).
   *
   * Reads get three attempts for weaker reasons. So does this now.
   *
   * Retrying is safe: minting is not a purchase. It writes a session row and
   * touches no order, payment or provider, so the worst case of a retried cold
   * start is two short-lived rows where one was wanted.
   */
  async function openSession(initData) {
    let lastError = null;
    let primaryMs = null;

    for (let e = 0; e < endpoints.length; e += 1) {
      const endpoint = endpoints[e];
      const startedAt = now();

      for (let attempt = 0; attempt < SESSION_ATTEMPTS; attempt += 1) {
        try {
          const out = await once('/api/v1/tma/session', {
            method: 'POST', body: { init_data: initData }, auth: false, base: endpoint.base,
          });
          sessionToken = out.session_token;
          sessionExpiresAt = now() + (Number(out.expires_in) || 0) * 1000;
          telemetry({
            api_route: endpoint.name,
            path: '/api/v1/tma/session',
            primary_latency_ms: primaryMs,
            latency_ms: now() - startedAt,
            fallback_used: e > 0,
            fallback_reason: e > 0 ? (lastError && (lastError.code || `http_${lastError.status}`)) : null,
          });

          return out;
        } catch (err) {
          lastError = err;
          // A rejected initData is a verdict, not a blip: 401 means the
          // signature did not check out, and the other endpoint verifies it
          // against the same bot token and the same clock. Asking twice only
          // doubles the wait before telling the customer the same thing.
          if (!shouldFailOver(err)) throw err;

          if (attempt < SESSION_ATTEMPTS - 1) {
            await wait(SESSION_BACKOFF_MS[Math.min(attempt, SESSION_BACKOFF_MS.length - 1)]);
          }
        }
      }

      if (e === 0) primaryMs = now() - startedAt;
    }

    throw lastError;
  }

  const hasSession = () => Boolean(sessionToken) && now() < sessionExpiresAt;

  /* ---- catalogue (public, no session) ---- */

  // The same endpoint the website uses. §8.3 rejected a TMA twin of it, so this
  // is deliberately not a Mini-App-specific catalogue.
  const catalogue = () => request('/api/v1/retail/packages', { auth: false });

  /**
   * Price a promo code, server-side.
   *
   * THE SAME ENDPOINT THE WEBSITE USES — `/api/v1/retail/promo/quote`, already
   * allowlisted at the gateway, already rate-limited, already the one place
   * that knows about validity windows, usage limits, per-email limits,
   * first-purchase rules, country and package restrictions and the minimum
   * margin guard. The Mini App does not get its own promo system and must not:
   * two implementations of "is this code allowed" is two answers.
   *
   * `auth: false` because the route is public, exactly as it is for the site.
   * The session is irrelevant to what a code is worth.
   *
   * WHAT TRAVELS: the code, the package, the payment type and — only when it is
   * a real address — the email, because per-email and first-purchase limits
   * cannot be evaluated without it. NEVER an amount, a discount, a rate or a
   * cost. The client has nothing to say about price.
   */
  const promoQuote = ({ code, packageId, paymentType, email }) => request(
    '/api/v1/retail/promo/quote',
    {
      method: 'POST',
      auth: false,
      body: {
        promo_code: code,
        package_id: packageId,
        payment_type: paymentType,
        ...(email && /.+@.+\..+/.test(email) ? { email } : {}),
      },
    }
  );

  /**
   * The catalogue snapshot that ships with the site.
   *
   * Same origin, served by the Pages CDN, refreshed six times a day by CI — so
   * it neither waits for Render nor for the gateway, and it is the one path
   * that still works when both are unreachable. Prices in it are up to four
   * hours old, which is why anything drawn from it must say so (§9 S1: showing
   * a stale catalogue as fresh is not acceptable, because a price is a promise).
   *
   * Deliberately NOT routed through `request`: it is not an API call, it has no
   * endpoint to fail over to, and one attempt is the whole budget it deserves.
   */
  async function staticCatalogue() {
    // One attempt is the whole budget — but an attempt with no deadline is not
    // a budget. A CDN request that hangs used to leave the catalogue skeleton
    // on screen forever, because the caller awaits this promise and nothing
    // else was ever going to settle it.
    const ac = typeof AbortController === 'function' ? new AbortController() : null;
    const timer = ac ? setTimeout(() => ac.abort(), STATIC_CATALOGUE_TIMEOUT_MS) : null;

    let res;
    try {
      res = await doFetch('../assets/catalog.json', {
        headers: { Accept: 'application/json' },
        signal: ac ? ac.signal : undefined,
      });
    } finally {
      if (timer) clearTimeout(timer);
    }
    if (!res.ok) throw new ApiError(res.status, 'STATIC_CATALOGUE', 'snapshot unavailable', null);
    const json = await res.json();

    // Normalised to the live envelope so no caller has to know where it came from.
    return {
      status: 'success',
      count: json.package_count || (json.packages || []).length,
      currency: 'RUB',
      data: json.packages || [],
      generated_at: json.generated_at || null,
    };
  }

  /* ---- the customer's own things ---- */

  const me = () => request('/api/v1/tma/me');
  const orders = (params = '') => request(`/api/v1/tma/me/orders${params}`);
  const activeOrders = () => request('/api/v1/tma/me/orders/active');

  /**
   * What this eSIM could be topped up with.
   *
   * A GET, and read-only on the server too: it creates no intent and calls no
   * provider write. The answer carries `purchase_enabled`, which is how the
   * app learns that real options exist while buying one is not open yet — the
   * client is told rather than finding out at a payment step that refuses.
   *
   * A 404 here is an eSIM that is not ours or does not exist; the server
   * answers both identically on purpose, so this does not try to tell them
   * apart either.
   */
  const topups = (esimId) => request(`/api/v1/tma/esims/${encodeURIComponent(esimId)}/topups`);

  /**
   * Price one top-up option and mint the intent behind it.
   *
   * What travels is the whole security model, and it is deliberately almost
   * nothing: the eSIM's own id, an OPAQUE option id that came from `topups`
   * above, a payment method and a real acceptance. There is no field here for a
   * price, a package code, an ICCID or a provider — the server re-derives all of
   * it from a live provider list, so the screen cannot sell something the
   * provider has withdrawn and cannot name a price of its own.
   *
   * NOT idempotent-retryable: a quote creates a row, and a repeat that crossed
   * with the first would leave two. A failed quote is safe to re-tap by hand —
   * the customer has paid nothing.
   */
  const topupQuote = (esimId, choice) => request(
    `/api/v1/tma/esims/${encodeURIComponent(esimId)}/topups/quote`,
    {
      method: 'POST',
      body: {
        option_id: choice.option_id,
        payment_type: choice.payment_type,
        // Reported, never asserted. The pay button stays disabled until the box
        // is ticked, so a `false` here means something went wrong and the
        // server should refuse — which it does.
        terms_accepted: choice.terms_accepted === true,
      },
    }
  );

  /**
   * Turn a quote into a payment link.
   *
   * NO BODY AT ALL, and that is the contract rather than an omission: the
   * option, the price, the method and the consent were settled at quote time
   * and live on the intent. There is nothing left for this call to get wrong.
   *
   * `idempotent: true` without a key, and it is safe for a better reason than
   * a key would be: the server keys on the INTENT. A repeat finds the order
   * this intent already has and returns the SAME payment link rather than
   * asking Platega for a second transaction.
   */
  const topupCheckout = (publicToken) => request(
    `/api/v1/tma/topups/${encodeURIComponent(publicToken)}/checkout`,
    { method: 'POST', idempotent: true, body: {} }
  );

  /**
   * Where a top-up stands.
   *
   * The ONLY source of that answer. Coming back from the payment browser proves
   * nothing — the return URL is not payment truth — so the app re-asks under
   * its own session and shows what the server says.
   */
  const topupStatus = (publicToken) => request(
    `/api/v1/tma/topups/${encodeURIComponent(publicToken)}/status`
  );

  /* ---- S13: purchases made on the website ---- */

  /**
   * Ask for a code.
   *
   * The answer is the same whatever happened to somebody ELSE'S address — sent,
   * rate limited, malformed, already another customer's — so there is nothing
   * to branch on there and this function offers none.
   *
   * The ONE exception is `status: 'already_verified'`: an address this customer
   * has themselves proven. That is a fact about their own account, not an
   * oracle, and it has to be distinguishable or the screen sends them to wait
   * for a code the server deliberately never sent.
   */
  const requestEmailCode = (email) => request('/api/v1/tma/identity/email/request', {
    method: 'POST', body: { email },
  });

  /**
   * Confirm it. This one CAN fail meaningfully: the person holding the session
   * already proved they asked, so «wrong code» and «expired» are worth telling
   * apart — one means retype, the other means start over.
   */
  const confirmEmailCode = (email, code) => request('/api/v1/tma/identity/email/confirm', {
    method: 'POST', body: { email, code },
  });
  /**
   * Disconnect a proven address.
   *
   * POST, not DELETE — the gateway forwards only GET and POST, which is also
   * why the backend route is a POST. The identity id names WHICH address; the
   * server still scopes the write to the session's customer, so the id
   * authorises nothing on its own.
   */
  /**
   * Turn one notification type on or off.
   *
   * Only the switch that changed is sent. An absent field means "leave it
   * alone" on the server, so the two toggles cannot overwrite each other —
   * which matters because they are rendered from one payload and tapped one at
   * a time.
   */
  const setNotificationPrefs = (patch) => request('/api/v1/tma/notifications/prefs', {
    method: 'POST', body: patch,
  });

  /**
   * Record the language the customer just CHOSE.
   *
   * Called only from the switcher, never from detection: what Telegram says a
   * client is set to is a guess about a person, and the backend deliberately
   * refuses to store one.
   */
  const setLanguage = (lang) => request('/api/v1/tma/settings/language', {
    method: 'POST', body: { lang },
  });

  const revokeEmail = (identityId) => request('/api/v1/tma/identity/email/revoke', {
    method: 'POST', body: { identity_id: identityId },
  });
  const orderStatus = (token) => request(`/api/v1/tma/orders/${encodeURIComponent(token)}/status`);
  const esims = () => request('/api/v1/tma/esims');
  const hiddenEsims = () => request('/api/v1/tma/esims/hidden');

  /**
   * The customer's own name for their own eSIM, and whether it shows in the
   * main list. Both are POST because the gateway forwards only GET and POST —
   * and DELETE would be the wrong verb for `visibility` in any case: nothing is
   * deleted by either call.
   *
   * An empty `name` clears the custom one. The server decides that, not this
   * function: it sends what the customer typed.
   */
  const renameEsim = (id, name) => request(
    `/api/v1/tma/esims/${encodeURIComponent(id)}/name`, { method: 'POST', body: { name } }
  );
  const setEsimVisibility = (id, hidden) => request(
    `/api/v1/tma/esims/${encodeURIComponent(id)}/visibility`,
    { method: 'POST', body: { hidden: Boolean(hidden) } }
  );
  const esim = (id) => request(`/api/v1/tma/esims/${encodeURIComponent(id)}`);

  // POST, but it creates nothing — see the route comment. Retryable as a read is
  // wrong (it is a POST), so it gets the write policy without a key: one shot.
  const activation = (id) => request(
    `/api/v1/tma/esims/${encodeURIComponent(id)}/activation`, { method: 'POST', body: {} }
  );

  const refreshUsage = (id) => request(
    `/api/v1/tma/esims/${encodeURIComponent(id)}/usage/refresh`, { method: 'POST', body: {} }
  );

  /**
   * Buy. The only call in this file that can spend money.
   *
   * `idempotent: true` is what makes the single retry safe, and the key comes
   * from the INTENT rather than from this call — so a retry, a double tap and a
   * resumed screen all reuse it.
   */
  async function purchase(intent) {
    const key = purchaseIntentKey(intent, storage, randomHex);

    return request('/api/v1/tma/orders', {
      method: 'POST',
      idempotent: true,
      body: {
        package_id: intent.package_id,
        email: intent.email,
        payment_type: intent.payment_type,
        // Reported, never asserted. This was hardcoded `true`, which sent an
        // acceptance the customer had not given — §9 S4 and §14.6 both require
        // an explicit act, and a pre-ticked box is expressly not one. The
        // checkout will not enable its pay button until the box is ticked, so a
        // false here means something went wrong and the server should refuse.
        terms_accepted: intent.terms_accepted === true,
        promo_code: intent.promo_code || undefined,
        // Only for tariffs sold by the day. The server checks the term against
        // its own ladder and computes the amount; this is a person's choice,
        // not a price — the app still calculates nothing.
        days: intent.days || undefined,
        // An assertion about what was shown, never an instruction. The server
        // prices the order and refuses if this disagrees.
        expected_amount_rub: intent.expected_amount_rub,
        idempotency_key: key,
      },
    });
  }

  /**
   * One funnel event. Fire and forget, by design and without exception.
   *
   * WHY THIS EXISTS AT ALL. The Mini App had no analytics of any kind, so
   * «people opened it» and «people got as far as pressing pay» were the same
   * unknown. Five names close that.
   *
   * WHY IT IS OURS RATHER THAN YANDEX METRIKA. The app runs under
   * `default-src 'none'` with `script-src 'self' https://telegram.org`. Letting
   * a third-party recorder into an authenticated surface that also holds the
   * payment redirect is a bigger concession than one append-only table of our
   * own. The website keeps Metrika; the two funnels are compared by event name.
   *
   * WHAT IT MUST NEVER DO. Block, throw, retry, or be awaited by anything a
   * customer is waiting on. Every call site fires it and walks away, the
   * promise is swallowed here, and `keepalive` lets the request outlive the
   * screen that started it. A Mini App that could be broken by its own
   * analytics would be a bad trade for any measurement.
   *
   * `payment_success` is deliberately not one of the names. A purchase is what
   * the Platega webhook says it is.
   */
  function track(event, props) {
    try {
      if (!sessionToken) return;               // unauthenticated: nothing to attribute
      const body = { event };
      if (props && props.country_code) body.country_code = props.country_code;
      if (props && props.payment_method) body.payment_method = props.payment_method;

      // Not `request()`, and not even `once()`: both layers retry, throw and
      // classify. None of that is wanted here — a lost event is cheaper than a
      // retried one, and an event that can throw is an event that can break a
      // screen. The primary endpoint only: no failover for a counter.
      //
      // But once() is ALSO where the abort timer lives, and skipping it left
      // this as the only request in the app with no timeout — a beacon on a bad
      // foreign network hanging indefinitely, in a keepalive pool that is
      // finite. So the timer comes along; the retry does not.
      const controller = typeof AbortController === 'function' ? new AbortController() : null;
      const timer = controller ? setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS) : null;

      doFetch(endpoints[0].base + '/api/v1/tma/events', {
        method: 'POST',
        keepalive: true,
        headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${sessionToken}` },
        body: JSON.stringify(body),
        signal: controller ? controller.signal : undefined,
      })
        .catch(() => {})
        .then(() => { if (timer) clearTimeout(timer); });
    } catch (_) { /* analytics is never a reason for anything to fail */ }
  }

  return {
    openSession, hasSession, catalogue, staticCatalogue, me, orders, activeOrders, orderStatus,
    topups, topupQuote, topupCheckout, topupStatus, requestEmailCode, confirmEmailCode,
    hiddenEsims, renameEsim, setEsimVisibility, revokeEmail, promoQuote, setNotificationPrefs,
    setLanguage,
    esims, esim, activation, refreshUsage, purchase, track,
    forgetIntent: (intent) => clearIntentKey(intent, storage),
    get token() { return sessionToken; },
  };
}

/* --------------------------------------------------------------------------
 * A read-through cache that is honest about staleness
 * ----------------------------------------------------------------------- */

/**
 * Serve the last good answer when the network will not cooperate.
 *
 * This is the concrete answer to TD-55 in the UI: a customer who opens "my
 * eSIMs" on a bad minute sees their eSIMs with a quiet "shown from cache" line,
 * not an error and not a spinner. What it must never do is hide a failure on a
 * WRITE, so only reads go through here.
 */
function createCache(storage, { now = () => Date.now() } = {}) {
  const KEY = (name) => `mesim.cache.${name}`;

  return {
    read(name, maxAgeMs) {
      try {
        const raw = storage.getItem(KEY(name));
        if (!raw) return null;
        const parsed = JSON.parse(raw);
        const age = now() - Number(parsed.at || 0);
        if (maxAgeMs && age > maxAgeMs) return { value: parsed.value, age, expired: true };

        return { value: parsed.value, age, expired: false };
      } catch {
        return null;
      }
    },
    write(name, value) {
      try {
        storage.setItem(KEY(name), JSON.stringify({ at: now(), value }));
      } catch {
        // A full or disabled storage must not break the app. Losing the cache
        // costs a spinner; throwing here costs the screen.
      }
    },
  };
}

/**
 * Fetch, and fall back to cache with the staleness made visible.
 *
 * Returns { value, stale, error } so a caller cannot accidentally present cached
 * data as fresh — the flag is in the same object as the data.
 */
async function readThrough(cache, name, fetcher) {
  try {
    const value = await fetcher();
    cache.write(name, value);

    return { value, stale: false, error: null };
  } catch (err) {
    const cached = cache.read(name);
    if (cached) return { value: cached.value, stale: true, error: err, age: cached.age };

    return { value: null, stale: false, error: err };
  }
}

