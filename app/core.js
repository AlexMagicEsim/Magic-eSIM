/**
 * A country name in the asked-for language. Never blank.
 *
 * English falls back to RUSSIAN before it falls back to the bare code, which is
 * the same rule app/i18n.js holds for every other string: «Бруней» is worse
 * than "Brunei" for an English reader, but it is far better than "BN".
 */
function countryLabel(code, lang) {
  const key = String(code || '').toUpperCase();
  if (lang === 'en') return countryNamesEn[key] || countryNames[key] || key;

  return countryNames[key] || key;
}

/** The flag the catalogue already carries, or one derived from the ISO code. */
function flagFor(code, pkg) {
  if (pkg && pkg.coverage_flags && String(pkg.coverage_flags).trim()) {
    // Regional packages carry a whole string of them; one flag is a label, ten
    // are noise on a 375px screen.
    const flags = [...String(pkg.coverage_flags).trim()];
    if (flags.length <= 4) return String(pkg.coverage_flags).trim();
  }
  const key = String(code || '').toUpperCase();
  if (!/^[A-Z]{2}$/.test(key)) return '';

  return key.replace(/[A-Z]/g, (ch) => String.fromCodePoint(127397 + ch.charCodeAt(0)));
}

/** A package covering more than one country is a regional offer, not a local one. */
function isRegional(pkg) {
  return Array.isArray(pkg && pkg.coverage_country_codes) && pkg.coverage_country_codes.length > 1;
}

/** "3 тарифа" — Russian needs three forms and "1 тарифов" reads as a bug. */
function plural(n, one, few, many) {
  const abs = Math.abs(Number(n) || 0);
  const mod10 = abs % 10;
  const mod100 = abs % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;

  return many;
}

const tariffWord = (n) => `${n} ${plural(n, 'тариф', 'тарифа', 'тарифов')}`;
const countryWord = (n) => `${n} ${plural(n, 'страна', 'страны', 'стран')}`;

/**
 * English has two forms, not three, so it gets its own selector rather than
 * being squeezed through plural()'s (one, few, many).
 *
 * Only 1 is singular. Zero is plural in English — "0 countries", not
 * "0 country" — which is the one case a naive `n > 1` gets wrong.
 */
function pluralEn(n, one, many) {
  return Math.abs(Number(n) || 0) === 1 ? one : many;
}

const tariffWordEn = (n) => `${n} ${pluralEn(n, 'plan', 'plans')}`;
const countryWordEn = (n) => `${n} ${pluralEn(n, 'country', 'countries')}`;

/** The provider's family name, normalised to a REGION_NAMES key. */
function regionKey(pkg) {
  return String((pkg && pkg.name) || '')
    .replace(/\s*\d+\s*GB[\s\S]*$/i, '')     // "Africa 5GB 30Days" -> "Africa"
    .replace(/\s*\(\d+\+?\s*areas?\)/i, '')  // "Global (120+ areas)" -> "Global"
    .replace(/\s+Unlimited[\s\S]*$/i, '')    // "EUconnect Unlimited 7 Days" -> "EUconnect"
    .replace(/\s+Premium$/i, ' Premium')
    .trim()
    .toUpperCase();
}

function regionLabel(pkg, lang) {
  const key = regionKey(pkg);
  const named = lang === 'en' ? (REGION_NAMES_EN[key] || REGION_NAMES[key]) : REGION_NAMES[key];
  if (named) return named;
  const n = (pkg && pkg.coverage_country_codes && pkg.coverage_country_codes.length) || 0;
  if (lang === 'en') return n ? `Region · ${countryWordEn(n)}` : 'Region';

  return n ? `Регион · ${countryWord(n)}` : 'Регион';
}

function byCountry(packages, lang) {
  const map = new Map();
  for (const p of (Array.isArray(packages) ? packages : [])) {
    // A catalogue is external input. One malformed row must cost that row, not
    // the screen.
    if (!p || typeof p !== 'object') continue;
    const code = String(p.country_code || '').toUpperCase();
    if (!code) continue;
    if (!map.has(code)) {
      map.set(code, {
        country_code: code,
        country: countryLabel(code, lang),
        flag: flagFor(code, p),
        items: [],
      });
    }
    map.get(code).items.push(p);
  }

  for (const group of map.values()) {
    group.items.sort((a, b) => Number(a.price) - Number(b.price));
    group.from = groupFrom(group.items);
    group.best = pickBestValue(group.items);
  }

  return [...map.values()].sort((a, b) => String(a.country).localeCompare(String(b.country), 'ru'));
}

/**
 * S1's data model: local destinations and regional offers are different things
 * and the Blueprint lists them as separate sections (§9 S1, items 4 and 5).
 *
 * Splitting them also fixes a lie the flat grouping told. A regional package is
 * filed under one member country, so "Vietnam Plus" — six countries — appeared
 * as an Indonesian tariff, and "EU" (34 countries) as an Andorran one.
 */
function groupCatalogue(packages, lang) {
  const rows = (Array.isArray(packages) ? packages : []).filter((p) => p && typeof p === 'object');
  const local = rows.filter((p) => !isRegional(p));
  const wide = rows.filter(isRegional);

  const regions = new Map();
  for (const p of wide) {
    const label = regionLabel(p, lang);
    if (!regions.has(label)) {
      regions.set(label, {
        country_code: String(p.country_code || '').toUpperCase(),
        country: label,
        // A handful of flags still reads as a place; twenty-nine of them is a
        // smear, and a globe says "region" better than a truncated list.
        flag: (p.coverage_country_codes || []).length <= 3
          ? flagFor(p.country_code, p)
          : '🌍',
        regional: true,
        coverage: (p.coverage_country_codes || []).slice(),
        items: [],
      });
    }
    const g = regions.get(label);
    g.items.push(p);
    // Keep the widest coverage we have seen for this family: the customer is
    // choosing a region, and the honest count is the biggest one it sells.
    if ((p.coverage_country_codes || []).length > g.coverage.length) {
      g.coverage = p.coverage_country_codes.slice();
    }
  }

  const finish = (g) => {
    g.items.sort((a, b) => Number(a.price) - Number(b.price));
    g.from = groupFrom(g.items);
    g.best = pickBestValue(g.items);

    return g;
  };

  return {
    countries: byCountry(local, lang),
    regions: [...regions.values()].map(finish)
      .sort((a, b) => (b.coverage.length - a.coverage.length)),
  };
}

/**
 * Regional offers that cover a given country.
 *
 * Blueprint §9 S2: a country with no local tariff is "не ошибка, а тупик, из
 * которого нужен выход" — and even where local tariffs exist, a traveller
 * crossing borders is better served by knowing the regional one exists.
 */
function regionsCovering(regions, code) {
  const key = String(code || '').toUpperCase();

  return (regions || [])
    .filter((r) => (r.coverage || []).some((c) => String(c).toUpperCase() === key))
    .sort((a, b) => Number(a.from) - Number(b.from));
}

function pickBestValue(items) {
  const usable = (items || []).filter((p) => Number(p.data_gb) > 0 && Number(p.price) > 0);
  if (!usable.length) return null;
  const scored = usable
    .map((p) => ({ p, perGb: Number(p.price) / Number(p.data_gb) }))
    .sort((a, b) => a.perGb - b.perGb);

  return scored[0].p;
}

/** Free-text country search that tolerates the way people actually type. */
/**
 * Fold a string down to something two people typing the same country will agree
 * on: case, surrounding space, ё/е, and the composed/decomposed forms macOS and
 * Android keyboards disagree about for й.
 */
function normalize(text) {
  return String(text == null ? '' : text)
    .normalize('NFC')
    .toLowerCase()
    .replace(/ё/g, 'е')
    // й -> и is not pedantry. The country is spelled «Таиланд», but a great many
    // people type «Тайланд», and «тай» — the obvious short form — matches
    // neither without this fold. It also makes «Йемен»/«Иемен» agree.
    .replace(/й/g, 'и')
    .replace(/[‐-―]/g, '-')  // ‑ – — typed by iOS autocorrect
    .trim();
}

/**
 * Free-text search that tolerates the way people actually type.
 *
 * Matches the Russian name, the Latin slug, and — last — the ISO code. The slug
 * is why "thailand" and "uae" work at all: the list is in Russian, and somebody
 * already abroad may well be on a Latin keyboard. The code is accepted because
 * it costs nothing and someone will try it, but it is never a display value and
 * never the reason a row is offered first.
 */
function searchCountries(groups, query) {
  const q = normalize(query);
  if (!q) return groups;

  // Ranked, not merely filtered. «тай» legitimately matches both «Таиланд» and
  // «Ки-тай»; which one is offered first is the whole difference between search
  // that works and search that technically works.
  //
  //   0  the name starts with what was typed
  //   1  the Latin slug starts with it
  //   2  the name or slug contains it
  //   3  a regional group whose coverage contains a match
  //   4  the ISO code — accepted, never promoted
  const rank = (g) => {
    const name = normalize(g.country);
    const code = String(g.country_code || '').toUpperCase();
    const slug = normalize(countryLatin[code] || '').replace(/-/g, ' ');
    const ql = q.replace(/-/g, ' ');

    if (name.startsWith(q)) return 0;
    // A regional group is filed under one member country, so it carries that
    // country's code and slug — «Большой Китай и Тайвань» is stored under CN.
    // Letting it match on those made "china" offer the region above China
    // itself. A region earns its place by its own name or by its coverage.
    if (!g.regional) {
      if (slug && slug.startsWith(ql)) return 1;
      if (name.includes(q) || slug && slug.includes(ql)) return 2;
    } else if (name.includes(q)) {
      return 2;
    }
    if (g.regional && (g.coverage || []).some((c) => {
      const cc = String(c).toUpperCase();
      const cs = normalize(countryLatin[cc] || '');
      return normalize(countryLabel(cc)).includes(q) || (cs && cs.includes(ql));
    })) return 3;
    if (!g.regional && code.toLowerCase().startsWith(q)) return 4;

    return -1;
  };

  const popularity = new Map(popularCountries.map((c, i) => [c, i]));

  return groups
    .map((g) => ({ g, r: rank(g) }))
    .filter((x) => x.r >= 0)
    .sort((a, b) => a.r - b.r
      || (popularity.get(a.g.country_code) ?? 99) - (popularity.get(b.g.country_code) ?? 99)
      || String(a.g.country).localeCompare(String(b.g.country), 'ru'))
    .map((x) => x.g);
}

/**
 * The storefront's popular destinations, in the storefront's order, reduced to
 * the ones we can actually sell today.
 *
 * The order is deliberately NOT re-sorted by price or name: it is an editorial
 * decision that lives on the website, and two surfaces disagreeing about what
 * is popular is worse than either order being imperfect.
 */
function popularGroups(countryGroups) {
  const byCode = new Map((countryGroups || []).map((g) => [g.country_code, g]));

  return popularCountries.map((code) => byCode.get(code)).filter(Boolean);
}

/**
 * §9 S2: «Сортировка: по умолчанию цена по возрастанию; переключатели по цене
 * и по объёму.»
 *
 * Two axes, because they answer two different questions. Price first is the
 * right default — it is what the list is scanned for — but a customer who
 * knows they need 20 GB is looking for volume and should not have to read
 * every card to find where it starts.
 *
 * Unlimited sorts above every finite volume rather than as some large number:
 * it is not a bigger amount, it is a different promise. Ties fall back to
 * price so the order is total and the list never reshuffles on a redraw.
 */
const TARIFF_SORTS = Object.freeze({
  price: { label: 'По цене', key: (p) => Number(p.price) || 0 },
  volume: { label: 'По объёму', key: (p) => (p.unlimited ? Infinity : Number(p.data_gb) || 0) },
});

function sortTariffs(items, sort = 'price') {
  const spec = TARIFF_SORTS[sort] || TARIFF_SORTS.price;
  const list = Array.isArray(items) ? items.slice() : [];
  // Volume descending (more is what is being looked for), price ascending.
  const dir = sort === 'volume' ? -1 : 1;

  return list.sort((a, b) => (dir * (spec.key(a) - spec.key(b)))
    || (Number(a.price) - Number(b.price))
    || String(a.package_id).localeCompare(String(b.package_id)));
}

/**
 * §9 S9: «Отметка времени обязательна ВСЕГДА — и когда данные свежие тоже.»
 *
 * "Осталось 3.2 ГБ" is a claim about a number the provider owns and we merely
 * relayed, possibly hours ago. Without a time next to it, the product is
 * making a promise it does not control. With one, the same number is a fact
 * about when we asked — which is true, and is what a traveller checking their
 * balance in an airport actually needs to know.
 *
 * Relative, because the absolute time answers the wrong question: nobody cares
 * that it was 14:02, only that it was ten minutes ago.
 */
function syncedAgo(iso, now = Date.now(), lang) {
  const en = lang === 'en';
  if (!iso) return en ? 'not requested yet' : 'данные ещё не запрашивались';
  const t = Date.parse(iso);
  if (!Number.isFinite(t)) return en ? 'last checked at an unknown time' : 'время последней проверки неизвестно';

  const mins = Math.floor((now - t) / 60000);
  if (mins < 0) return en ? 'just now' : 'только что';
  if (mins < 1) return en ? 'updated just now' : 'обновлено только что';
  if (mins < 60) {
    return en
      ? `updated ${mins} ${pluralEn(mins, 'minute', 'minutes')} ago`
      : `обновлено ${mins} ${plural(mins, 'минуту', 'минуты', 'минут')} назад`;
  }

  const hours = Math.floor(mins / 60);
  if (hours < 24) {
    return en
      ? `updated ${hours} ${pluralEn(hours, 'hour', 'hours')} ago`
      : `обновлено ${hours} ${plural(hours, 'час', 'часа', 'часов')} назад`;
  }

  const days = Math.floor(hours / 24);

  return en
    ? `updated ${days} ${pluralEn(days, 'day', 'days')} ago`
    : `обновлено ${days} ${plural(days, 'день', 'дня', 'дней')} назад`;
}

/**
 * Which set of installation steps to open on.
 *
 * §9 S10 asks for `Telegram.WebApp.platform` rather than the user agent, and
 * the reason is concrete: inside a WebView the UA describes the engine, so an
 * Android tablet running a WebKit-flavoured browser, or any client Telegram
 * has not taught us about, lands on the wrong instructions. Telegram knows
 * which client it is. The manual switch stays either way — detection is
 * allowed to be wrong, a customer stuck on the wrong steps is not.
 */
function installPlatform(tgPlatform, userAgent) {
  const p = String(tgPlatform || '').toLowerCase();
  if (p === 'ios' || p === 'macos') return 'ios';
  if (p === 'android' || p === 'android_x') return 'android';
  // 'tdesktop', 'weba', 'webk', 'unknown' and anything new: Telegram is not
  // telling us about a phone, so fall back to what the browser says.
  if (/iPhone|iPad|iPod/i.test(String(userAgent || ''))) return 'ios';

  return 'android';
}

